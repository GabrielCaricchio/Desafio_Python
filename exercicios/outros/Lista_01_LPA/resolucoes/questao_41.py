numero=float(input("Informe um valor:"))
if numero==5:
    print("O número é igual a 5")
elif numero==200:
    print("O número é igual a 200")
elif numero==400:
    print("O número é igual a 400")
elif numero>500 and numero<1000:
   print("O número está entre 500 e 1000")
else:
    print("O número não é igual a 5,200,400, e não está entre 500 e 1000")